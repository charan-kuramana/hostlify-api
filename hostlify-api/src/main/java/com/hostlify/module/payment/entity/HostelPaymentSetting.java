package com.hostlify.module.payment.entity;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * Owner-controlled payment settings for one hostel: due day, reminders, optional late fee,
 * direct-UPI details and landlord details printed on HRA rent receipts.
 * A hostel without a row uses the defaults below (see PaymentSettingsService#getOrDefault).
 */
@Getter
@Setter
@Entity
@Table(name = "hostel_payment_settings")
public class HostelPaymentSetting {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "hostel_id", nullable = false, unique = true)
    private Long hostelId;

    /** Day of month rent is due (1-28). */
    @Column(name = "due_day", nullable = false)
    private int dueDay = 20;

    /** Create next month's rent dues automatically on the 1st. */
    @Column(name = "auto_generate_dues", nullable = false)
    private boolean autoGenerateDues = true;

    /** Remind N days before the due date (0 = off). */
    @Column(name = "reminder_days_before", nullable = false)
    private int reminderDaysBefore = 3;

    @Column(name = "remind_on_due_date", nullable = false)
    private boolean remindOnDueDate = true;

    /** After the due date, remind every N days until paid (0 = off). */
    @Column(name = "overdue_reminder_interval_days", nullable = false)
    private int overdueReminderIntervalDays = 3;

    /** Owner's choice: late fee is OFF unless the owner turns it on. */
    @Column(name = "late_fee_enabled", nullable = false)
    private boolean lateFeeEnabled = false;

    /** Set when the owner switches the late fee on: only rent due on/after this date is charged. */
    @Column(name = "late_fee_enabled_on")
    private java.time.LocalDate lateFeeEnabledOn;

    /** FLAT (one-time) | PER_DAY (per day late, after grace). */
    @Column(name = "late_fee_type", nullable = false, length = 10)
    private String lateFeeType = "FLAT";

    @Column(name = "late_fee_amount", nullable = false, precision = 12, scale = 2)
    private BigDecimal lateFeeAmount = BigDecimal.ZERO;

    /** Days after the due date before any late fee applies. */
    @Column(name = "late_fee_grace_days", nullable = false)
    private int lateFeeGraceDays = 5;

    /** Cap for PER_DAY late fees (null = no cap). */
    @Column(name = "late_fee_max_amount", precision = 12, scale = 2)
    private BigDecimal lateFeeMaxAmount;

    @Column(name = "upi_id", length = 100)
    private String upiId;

    @Column(name = "upi_payee_name", length = 100)
    private String upiPayeeName;

    @Column(name = "landlord_name", length = 150)
    private String landlordName;

    /** Needed on HRA receipts when annual rent exceeds Rs 1,00,000. */
    @Column(name = "landlord_pan", length = 10)
    private String landlordPan;

    @Column(name = "landlord_address", columnDefinition = "TEXT")
    private String landlordAddress;

    @Column(name = "created_at", insertable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at", insertable = false)
    private LocalDateTime updatedAt;
}
