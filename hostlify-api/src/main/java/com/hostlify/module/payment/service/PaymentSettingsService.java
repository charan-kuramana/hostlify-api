package com.hostlify.module.payment.service;

import com.hostlify.module.payment.entity.HostelPaymentSetting;
import com.hostlify.module.payment.repository.HostelPaymentSettingRepository;
import com.hostlify.shared.exception.AppException;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.regex.Pattern;

@Service
public class PaymentSettingsService {

    private static final Pattern UPI_ID = Pattern.compile("^[a-zA-Z0-9.\\-_]{2,256}@[a-zA-Z]{2,64}$");
    private static final Pattern PAN = Pattern.compile("^[A-Z]{5}[0-9]{4}[A-Z]$");

    private final HostelPaymentSettingRepository repo;

    public PaymentSettingsService(HostelPaymentSettingRepository repo) {
        this.repo = repo;
    }

    /** Saved settings, or an unsaved instance with defaults (late fee off, due on the 20th). */
    public HostelPaymentSetting getOrDefault(Long hostelId) {
        return repo.findByHostelId(hostelId).orElseGet(() -> {
            HostelPaymentSetting s = new HostelPaymentSetting();
            s.setHostelId(hostelId);
            return s;
        });
    }

    @Transactional
    public HostelPaymentSetting update(Long hostelId, Map<String, Object> body) {
        HostelPaymentSetting s = getOrDefault(hostelId);

        if (body.containsKey("dueDay")) s.setDueDay(intIn(body.get("dueDay"), 1, 28, "Due day must be between 1 and 28"));
        if (body.containsKey("autoGenerateDues")) s.setAutoGenerateDues(Boolean.TRUE.equals(body.get("autoGenerateDues")));
        if (body.containsKey("reminderDaysBefore")) s.setReminderDaysBefore(intIn(body.get("reminderDaysBefore"), 0, 15, "Reminder days before must be 0-15"));
        if (body.containsKey("remindOnDueDate")) s.setRemindOnDueDate(Boolean.TRUE.equals(body.get("remindOnDueDate")));
        if (body.containsKey("overdueReminderIntervalDays")) s.setOverdueReminderIntervalDays(intIn(body.get("overdueReminderIntervalDays"), 0, 30, "Overdue reminder interval must be 0-30 days"));

        if (body.containsKey("lateFeeEnabled")) {
            boolean on = Boolean.TRUE.equals(body.get("lateFeeEnabled"));
            // Turning it on never back-charges dues that were already late
            if (on && !s.isLateFeeEnabled()) s.setLateFeeEnabledOn(com.hostlify.shared.util.DateUtils.todayKolkata());
            s.setLateFeeEnabled(on);
        }
        if (body.containsKey("lateFeeType")) {
            String t = String.valueOf(body.get("lateFeeType")).toUpperCase();
            if (!t.equals("FLAT") && !t.equals("PER_DAY")) throw bad("Late fee type must be FLAT or PER_DAY");
            s.setLateFeeType(t);
        }
        if (body.containsKey("lateFeeAmount")) s.setLateFeeAmount(money(body.get("lateFeeAmount"), false, "Late fee amount"));
        if (body.containsKey("lateFeeGraceDays")) s.setLateFeeGraceDays(intIn(body.get("lateFeeGraceDays"), 0, 30, "Grace days must be 0-30"));
        if (body.containsKey("lateFeeMaxAmount")) s.setLateFeeMaxAmount(money(body.get("lateFeeMaxAmount"), true, "Late fee cap"));
        if (s.isLateFeeEnabled() && s.getLateFeeAmount().signum() <= 0) {
            throw bad("Enter a late fee amount greater than 0, or turn the late fee off");
        }

        if (body.containsKey("upiId")) {
            String upi = trimToNull(body.get("upiId"));
            if (upi != null && !UPI_ID.matcher(upi).matches()) throw bad("Enter a valid UPI ID, e.g. name@okhdfcbank");
            s.setUpiId(upi);
        }
        if (body.containsKey("upiPayeeName")) s.setUpiPayeeName(limit(trimToNull(body.get("upiPayeeName")), 100));
        if (body.containsKey("landlordName")) s.setLandlordName(limit(trimToNull(body.get("landlordName")), 150));
        if (body.containsKey("landlordPan")) {
            String pan = trimToNull(body.get("landlordPan"));
            if (pan != null) {
                pan = pan.toUpperCase();
                if (!PAN.matcher(pan).matches()) throw bad("Enter a valid PAN, e.g. ABCDE1234F");
            }
            s.setLandlordPan(pan);
        }
        if (body.containsKey("landlordAddress")) s.setLandlordAddress(limit(trimToNull(body.get("landlordAddress")), 1000));

        s.setUpdatedAt(LocalDateTime.now());
        return repo.save(s);
    }

    /** What a resident of the hostel may see: how to pay and the late fee policy. */
    public Map<String, Object> residentView(Long hostelId) {
        HostelPaymentSetting s = getOrDefault(hostelId);
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("dueDay", s.getDueDay());
        m.put("upiId", s.getUpiId());
        m.put("upiPayeeName", s.getUpiPayeeName());
        m.put("lateFeeEnabled", s.isLateFeeEnabled());
        if (s.isLateFeeEnabled()) {
            m.put("lateFeeType", s.getLateFeeType());
            m.put("lateFeeAmount", s.getLateFeeAmount());
            m.put("lateFeeGraceDays", s.getLateFeeGraceDays());
            m.put("lateFeeMaxAmount", s.getLateFeeMaxAmount());
        }
        return m;
    }

    // ─── helpers ───────────────────────────────────────────────────────────

    private static int intIn(Object v, int min, int max, String msg) {
        try {
            int i = (int) Math.round(Double.parseDouble(String.valueOf(v)));
            if (i < min || i > max) throw bad(msg);
            return i;
        } catch (NumberFormatException e) {
            throw bad(msg);
        }
    }

    private static BigDecimal money(Object v, boolean nullable, String field) {
        if (v == null || String.valueOf(v).isBlank()) {
            if (nullable) return null;
            throw bad(field + " is required");
        }
        try {
            BigDecimal b = new BigDecimal(String.valueOf(v)).setScale(2, java.math.RoundingMode.HALF_UP);
            if (b.signum() < 0 || b.compareTo(new BigDecimal("1000000")) > 0) throw bad(field + " must be between 0 and 10,00,000");
            return b;
        } catch (NumberFormatException e) {
            throw bad(field + " must be a number");
        }
    }

    private static String trimToNull(Object v) {
        if (v == null) return null;
        String s = String.valueOf(v).trim();
        return s.isEmpty() ? null : s;
    }

    private static String limit(String s, int max) {
        return s == null || s.length() <= max ? s : s.substring(0, max);
    }

    private static AppException bad(String msg) {
        return new AppException(msg, HttpStatus.BAD_REQUEST);
    }
}
