package com.hostlify.module.ops;

import com.hostlify.module.expense.entity.ExpenseEmployee;
import com.hostlify.module.expense.entity.ExpenseSalaryRecord;
import com.hostlify.module.hostel.entity.Hostel;
import com.hostlify.module.hostel.repository.HostelRepository;
import com.lowagie.text.*;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import org.springframework.stereotype.Service;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.LocalDateTime;
import java.time.Month;
import java.time.format.DateTimeFormatter;
import java.time.format.TextStyle;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Stream;

/** Salary slip PDF for one recorded salary, with the attendance it was based on. */
@Service
public class SalarySlipPdfService {

    private static final DateTimeFormatter DT = DateTimeFormatter.ofPattern("dd MMM yyyy", Locale.ENGLISH);
    private static final Color BRAND = new Color(29, 110, 168);
    private static final Font TITLE = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 15, BRAND);
    private static final Font H = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10);
    private static final Font N = FontFactory.getFont(FontFactory.HELVETICA, 10);
    private static final Font SMALL = FontFactory.getFont(FontFactory.HELVETICA, 8, new Color(110, 110, 110));

    private final HostelRepository hostelRepo;

    public SalarySlipPdfService(HostelRepository hostelRepo) {
        this.hostelRepo = hostelRepo;
    }

    public byte[] slip(ExpenseSalaryRecord rec, ExpenseEmployee e, Map<String, Integer> counts) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        Document d = new Document(PageSize.A4, 46, 46, 40, 40);
        PdfWriter.getInstance(d, out);
        d.open();
        Hostel h = hostelRepo.findById(rec.getHostelId()).orElse(null);
        d.add(new Paragraph(h != null ? h.getName() : "Hostlify", FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12)));
        if (h != null) d.add(new Paragraph(11, String.join(", ", Stream.of(h.getAddress(), h.getCity(), h.getPincode())
                .filter(s -> s != null && !s.isBlank()).toList()), SMALL));
        String period = Month.of(rec.getPeriodMonth()).getDisplayName(TextStyle.FULL, Locale.ENGLISH) + " " + rec.getPeriodYear();
        Paragraph t = new Paragraph("Salary slip - " + period, TITLE);
        t.setAlignment(Element.ALIGN_CENTER);
        t.setSpacingBefore(10);
        t.setSpacingAfter(12);
        d.add(t);

        PdfPTable who = table();
        header(who, "Employee");
        row(who, "Name", e.getName());
        row(who, "Role", e.getRole());
        if (e.getEmployeeCode() != null) row(who, "Employee code", e.getEmployeeCode());
        if (e.getMobile() != null) row(who, "Mobile", e.getMobile());
        row(who, "Status", "PAID".equals(rec.getStatus()) ? "Paid" + (rec.getPaidAt() != null ? " on " + rec.getPaidAt().format(DT) : "") : "Pending");
        d.add(who);
        d.add(new Paragraph(" "));

        PdfPTable att = table();
        header(att, "Attendance");
        if (rec.getDaysInMonth() != null) {
            row(att, "Days in month", String.valueOf(rec.getDaysInMonth()));
            row(att, "Paid days", num(rec.getPaidDays()));
            row(att, "Absent days (incl. ½ for half days)", num(rec.getAbsentDays()));
        }
        row(att, "Present / Half day / Leave / Week off / Absent", counts.get("PRESENT") + " / " + counts.get("HALF_DAY") + " / "
                + counts.get("LEAVE") + " / " + counts.get("WEEK_OFF") + " / " + counts.get("ABSENT"));
        d.add(att);
        d.add(new Paragraph(" "));

        PdfPTable pay = table();
        header(pay, "Earnings and deductions (Rs.)");
        BigDecimal base = e.getBaseSalary() == null ? BigDecimal.ZERO : e.getBaseSalary();
        BigDecimal hra = e.getHra() == null ? BigDecimal.ZERO : e.getHra();
        line(pay, "Basic", base, false);
        if (hra.signum() > 0) line(pay, "HRA", hra, false);
        BigDecimal adj = rec.getGrossSalary().subtract(base.add(hra));
        if (adj.signum() != 0) line(pay, "Adjustment", adj, false);
        line(pay, "Gross pay", rec.getGrossSalary(), true);
        line(pay, "Deductions" + (rec.getDeductionNote() != null ? " (" + rec.getDeductionNote() + ")" : ""), rec.getDeductions(), false);
        line(pay, "Net pay", rec.getNetSalary(), true);
        d.add(pay);

        Paragraph f = new Paragraph(11, "Generated by Hostlify on " + LocalDateTime.now().format(DT)
                + ". This is a computer-generated slip and needs no signature.", SMALL);
        f.setSpacingBefore(14);
        d.add(f);
        d.close();
        return out.toByteArray();
    }

    private static String num(BigDecimal b) {
        return b == null ? "-" : b.stripTrailingZeros().toPlainString();
    }

    private static PdfPTable table() {
        PdfPTable t = new PdfPTable(new float[]{2.2f, 1.5f});
        t.setWidthPercentage(100);
        return t;
    }

    private static void header(PdfPTable t, String text) {
        PdfPCell c = new PdfPCell(new Phrase(text, FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9, Color.WHITE)));
        c.setBackgroundColor(BRAND);
        c.setBorderColor(BRAND);
        c.setPadding(5);
        c.setColspan(2);
        t.addCell(c);
    }

    private static void row(PdfPTable t, String k, String v) {
        t.addCell(cell(k, SMALL));
        t.addCell(cell(v == null ? "-" : v, N));
    }

    private static void line(PdfPTable t, String label, BigDecimal amount, boolean bold) {
        Font f = bold ? H : N;
        t.addCell(cell(label, f));
        PdfPCell c = cell(amount == null ? "0.00" : amount.setScale(2, RoundingMode.HALF_UP).toPlainString(), f);
        c.setHorizontalAlignment(Element.ALIGN_RIGHT);
        t.addCell(c);
    }

    private static PdfPCell cell(String text, Font f) {
        PdfPCell c = new PdfPCell(new Phrase(text, f));
        c.setPadding(5);
        c.setBorderColor(new Color(225, 225, 225));
        return c;
    }
}
