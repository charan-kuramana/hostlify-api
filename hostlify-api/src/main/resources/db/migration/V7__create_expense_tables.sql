CREATE TABLE expense_records (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hostel_id      BIGINT         NOT NULL,
  category       VARCHAR(30)    NOT NULL,
  amount         DECIMAL(12, 2) NOT NULL,
  description    VARCHAR(500),
  vendor_name    VARCHAR(200),
  invoice_number VARCHAR(100),
  invoice_url    VARCHAR(500),
  expense_date   DATE           NOT NULL,
  period_month   INT            NOT NULL,
  period_year    INT            NOT NULL,
  recorded_by    BIGINT         NOT NULL,
  created_at     TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted     BOOLEAN     NOT NULL DEFAULT FALSE,
  deleted_at     TIMESTAMP       DEFAULT NULL,
  CONSTRAINT fk_er_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id)
);
CREATE INDEX idx_er_hostel_id ON expense_records (hostel_id);
CREATE INDEX idx_er_period ON expense_records (period_year, period_month);
CREATE INDEX idx_er_category ON expense_records (category);

CREATE TABLE expense_employees (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hostel_id     BIGINT         NOT NULL,
  employee_code VARCHAR(30),
  name          VARCHAR(150)   NOT NULL,
  role          VARCHAR(80)    NOT NULL,
  mobile        VARCHAR(15),
  base_salary   DECIMAL(12, 2) NOT NULL,
  hra           DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
  created_at    TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted    BOOLEAN     NOT NULL DEFAULT FALSE,
  deleted_at    TIMESTAMP       DEFAULT NULL,
  CONSTRAINT fk_ee_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id)
);
CREATE INDEX idx_ee_hostel_id ON expense_employees (hostel_id);

CREATE TABLE expense_salary_records (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id  BIGINT         NOT NULL,
  hostel_id    BIGINT         NOT NULL,
  period_month INT            NOT NULL,
  period_year  INT            NOT NULL,
  gross_salary DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
  deductions   DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
  net_salary   DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
  status       VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
  paid_at      TIMESTAMP,
  created_at   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted   BOOLEAN     NOT NULL DEFAULT FALSE,
  deleted_at   TIMESTAMP       DEFAULT NULL,
  CONSTRAINT fk_esr_employee FOREIGN KEY (employee_id) REFERENCES expense_employees (id),
  CONSTRAINT fk_esr_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id)
);
CREATE INDEX idx_esr_employee_id ON expense_salary_records (employee_id);
CREATE INDEX idx_esr_hostel_id ON expense_salary_records (hostel_id);
CREATE INDEX idx_esr_period ON expense_salary_records (period_year, period_month);
CREATE INDEX idx_esr_status ON expense_salary_records (status);
