-- Section 5 "Owner operations": staff attendance, attendance-aware salary slips, room meter billing.

-- 1. Daily attendance for employees (cooks, cleaners, guards… from Staff & Employees).
CREATE TABLE staff_attendance (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id    BIGINT       NOT NULL,
    employee_id  BIGINT       NOT NULL,
    att_date     DATE         NOT NULL,
    status       VARCHAR(10)  NOT NULL,
    in_time      TIME         NULL,
    out_time     TIME         NULL,
    note         VARCHAR(150) NULL,
    marked_by    BIGINT       NOT NULL,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_sa_day UNIQUE (employee_id, att_date),
    CONSTRAINT fk_sa_employee FOREIGN KEY (employee_id) REFERENCES expense_employees (id),
    CONSTRAINT ck_sa_status CHECK (status IN ('PRESENT', 'ABSENT', 'HALF_DAY', 'LEAVE', 'WEEK_OFF'))
);
CREATE INDEX idx_sa_hostel_date ON staff_attendance (hostel_id, att_date);

-- 2. Salary slips remember the attendance they were based on.
ALTER TABLE expense_salary_records
    ADD COLUMN days_in_month  INT          NULL,
    ADD COLUMN paid_days      DECIMAL(5,1) NULL,
    ADD COLUMN absent_days    DECIMAL(5,1) NULL,
    ADD COLUMN deduction_note VARCHAR(200) NULL;

-- 3. Electricity / water meter readings per room per month, split across the room's residents.
CREATE TABLE meter_readings (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id         BIGINT         NOT NULL,
    room_id           BIGINT         NOT NULL,
    meter_type        VARCHAR(12)    NOT NULL,
    period_year       INT            NOT NULL,
    period_month      INT            NOT NULL,
    previous_reading  DECIMAL(12, 2) NOT NULL,
    current_reading   DECIMAL(12, 2) NOT NULL,
    units             DECIMAL(12, 2) NOT NULL,
    rate_per_unit     DECIMAL(8, 2)  NOT NULL,
    fixed_charge      DECIMAL(10, 2) NOT NULL DEFAULT 0,
    amount            DECIMAL(12, 2) NOT NULL,
    status            VARCHAR(10)    NOT NULL DEFAULT 'DRAFT', -- DRAFT | BILLED
    residents_billed  INT            NULL,
    billed_at         TIMESTAMP      NULL,
    created_by        BIGINT         NOT NULL,
    created_at        TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_mr_room_period UNIQUE (room_id, meter_type, period_year, period_month),
    CONSTRAINT fk_meter_room FOREIGN KEY (room_id) REFERENCES hostel_rooms (id),
    CONSTRAINT ck_meter_type CHECK (meter_type IN ('ELECTRICITY', 'WATER')),
    CONSTRAINT ck_meter_reading CHECK (current_reading >= previous_reading)
);
CREATE INDEX idx_meter_hostel_period ON meter_readings (hostel_id, period_year, period_month);
