CREATE TABLE booking_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hosteller_user_id BIGINT NOT NULL,
  hosteller_profile_id BIGINT NOT NULL,
  hostel_id BIGINT NOT NULL,
  bed_id BIGINT NOT NULL,
  room_id BIGINT NOT NULL,
  floor_id BIGINT NOT NULL,
  check_in_date DATE NOT NULL,
  preference_notes TEXT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'PENDING_APPROVAL',
  reviewed_by_staff_id BIGINT NULL,
  rejection_reason VARCHAR(500) NULL,
  reassigned_bed_id BIGINT NULL,
  expires_at TIMESTAMP NULL,
  booking_checkin_id BIGINT NULL,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  deleted_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_br_user FOREIGN KEY (hosteller_user_id) REFERENCES auth_users(id),
  CONSTRAINT fk_br_profile FOREIGN KEY (hosteller_profile_id) REFERENCES hosteller_profiles(id),
  CONSTRAINT fk_br_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels(id),
  CONSTRAINT fk_br_bed FOREIGN KEY (bed_id) REFERENCES hostel_beds(id),
  CONSTRAINT fk_br_room FOREIGN KEY (room_id) REFERENCES hostel_rooms(id),
  CONSTRAINT fk_br_floor FOREIGN KEY (floor_id) REFERENCES hostel_floors(id)
);
CREATE INDEX idx_br_hosteller ON booking_requests (hosteller_user_id);
CREATE INDEX idx_br_hostel ON booking_requests (hostel_id);
CREATE INDEX idx_br_bed ON booking_requests (bed_id);
CREATE INDEX idx_br_status ON booking_requests (status);
