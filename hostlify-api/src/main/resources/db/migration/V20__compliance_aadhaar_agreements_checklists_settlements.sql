-- Section 3 "Compliance & trust": Aadhaar Secure QR checks, rental agreements, move-in/out checklists,
-- deposit settlement. Police verification intentionally not included.

-- 1. Aadhaar rules: never keep full Aadhaar numbers. Mask what's already stored to the last 4 digits.
UPDATE hosteller_profiles
SET id_proof_number = 'XXXX-XXXX-' || right(regexp_replace(id_proof_number, '\D', '', 'g'), 4)
WHERE upper(id_proof_type) = 'AADHAAR'
  AND id_proof_number IS NOT NULL
  AND length(regexp_replace(id_proof_number, '\D', '', 'g')) >= 4
  AND id_proof_number NOT LIKE 'XXXX-XXXX-%';

-- 2. Aadhaar Secure QR verification results (minimal data; no number, photo or address).
CREATE TABLE identity_verifications (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hosteller_id        BIGINT       NOT NULL,
    hostel_id           BIGINT       NULL,
    method              VARCHAR(30)  NOT NULL DEFAULT 'AADHAAR_SECURE_QR',
    status              VARCHAR(20)  NOT NULL,              -- VERIFIED | FAILED
    failure_reason      VARCHAR(300) NULL,
    aadhaar_last4       VARCHAR(4)   NULL,
    name_on_aadhaar     VARCHAR(150) NULL,
    dob_on_aadhaar      VARCHAR(12)  NULL,
    gender_on_aadhaar   VARCHAR(10)  NULL,
    state_on_aadhaar    VARCHAR(60)  NULL,
    qr_generated_at     TIMESTAMP    NULL,
    name_matches        BOOLEAN      NULL,
    dob_matches         BOOLEAN      NULL,
    photo_confirmed_by  BIGINT       NULL,
    photo_confirmed_at  TIMESTAMP    NULL,
    consent_at          TIMESTAMP    NOT NULL,
    performed_by        BIGINT       NOT NULL,
    performed_by_role   VARCHAR(20)  NOT NULL,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_iv_hosteller FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id)
);
CREATE INDEX idx_iv_hosteller ON identity_verifications (hosteller_id, status);
CREATE INDEX idx_iv_hostel ON identity_verifications (hostel_id, status);

-- 3. Rental / licence agreements.
CREATE TABLE agreement_templates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id   BIGINT        NOT NULL,
    title       VARCHAR(150)  NOT NULL,
    body        TEXT          NOT NULL,
    notice_days INT           NOT NULL DEFAULT 30,
    updated_by  BIGINT        NULL,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_at_hostel UNIQUE (hostel_id),
    CONSTRAINT fk_at_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id)
);

CREATE TABLE rental_agreements (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id            BIGINT        NOT NULL,
    hosteller_id         BIGINT        NOT NULL,
    booking_id           BIGINT        NULL,
    title                VARCHAR(150)  NOT NULL,
    body                 TEXT          NOT NULL,          -- frozen, filled-in text the resident accepts
    body_sha256          VARCHAR(64)   NOT NULL,
    status               VARCHAR(20)   NOT NULL DEFAULT 'SENT',   -- SENT | ACCEPTED | VOID
    created_by           BIGINT        NOT NULL,
    sent_at              TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    otp_hash             VARCHAR(64)   NULL,
    otp_expires_at       TIMESTAMP     NULL,
    otp_attempts         INT           NOT NULL DEFAULT 0,
    accepted_at          TIMESTAMP     NULL,
    accepted_name        VARCHAR(150)  NULL,
    accepted_ip          VARCHAR(64)   NULL,
    accepted_user_agent  VARCHAR(300)  NULL,
    accepted_with_otp    BOOLEAN       NOT NULL DEFAULT FALSE,
    voided_at            TIMESTAMP     NULL,
    void_reason          VARCHAR(300)  NULL,
    CONSTRAINT fk_ra_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id),
    CONSTRAINT fk_ra_hosteller FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id)
);
CREATE INDEX idx_ra_hosteller ON rental_agreements (hosteller_id, status);
CREATE INDEX idx_ra_hostel ON rental_agreements (hostel_id, status);

-- 4. Move-in / move-out checklists with photos.
CREATE TABLE room_checklists (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id         BIGINT        NOT NULL,
    hosteller_id      BIGINT        NOT NULL,
    booking_id        BIGINT        NULL,
    kind              VARCHAR(10)   NOT NULL,                 -- MOVE_IN | MOVE_OUT
    status            VARCHAR(20)   NOT NULL DEFAULT 'DRAFT', -- DRAFT | SUBMITTED | ACKNOWLEDGED | DISPUTED
    items_json        TEXT          NOT NULL,                 -- [{key,label,condition,note}]
    keys_handed       INT           NULL,
    meter_reading     VARCHAR(30)   NULL,
    staff_notes       VARCHAR(2000) NULL,
    created_by        BIGINT        NOT NULL,
    submitted_at      TIMESTAMP     NULL,
    resident_response VARCHAR(20)   NULL,                     -- ACKNOWLEDGED | DISPUTED
    resident_comment  VARCHAR(1000) NULL,
    responded_at      TIMESTAMP     NULL,
    responded_ip      VARCHAR(64)   NULL,
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rc_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id),
    CONSTRAINT fk_rc_hosteller FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id),
    CONSTRAINT ck_rc_kind CHECK (kind IN ('MOVE_IN', 'MOVE_OUT'))
);
CREATE INDEX idx_rc_hosteller ON room_checklists (hosteller_id, kind);

CREATE TABLE checklist_photos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checklist_id  BIGINT       NOT NULL,
    blob_path     VARCHAR(500) NOT NULL,
    caption       VARCHAR(150) NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cp_checklist FOREIGN KEY (checklist_id) REFERENCES room_checklists (id)
);
CREATE INDEX idx_cp_checklist ON checklist_photos (checklist_id);

-- 5. Deposit settlement at checkout.
CREATE TABLE deposit_settlements (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id          BIGINT         NOT NULL,
    hosteller_id       BIGINT         NOT NULL,
    booking_id         BIGINT         NOT NULL,
    deposit_held       DECIMAL(12, 2) NOT NULL DEFAULT 0,
    deductions_json    TEXT           NOT NULL DEFAULT '[]',  -- [{label, amount}]
    unpaid_dues        DECIMAL(12, 2) NOT NULL DEFAULT 0,     -- open dues adjusted against the deposit
    refund_amount      DECIMAL(12, 2) NOT NULL DEFAULT 0,
    balance_due        DECIMAL(12, 2) NOT NULL DEFAULT 0,     -- still owed if deductions exceed the deposit
    status             VARCHAR(20)    NOT NULL DEFAULT 'DRAFT', -- DRAFT | FINALIZED | REFUNDED
    notes              VARCHAR(1000)  NULL,
    refund_method      VARCHAR(30)    NULL,
    refund_reference   VARCHAR(100)   NULL,
    finalized_by       BIGINT         NULL,
    finalized_at       TIMESTAMP      NULL,
    refunded_at        TIMESTAMP      NULL,
    created_at         TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ds_booking UNIQUE (booking_id),
    CONSTRAINT fk_ds_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id),
    CONSTRAINT fk_ds_hosteller FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id)
);
CREATE INDEX idx_ds_hostel ON deposit_settlements (hostel_id, status);
