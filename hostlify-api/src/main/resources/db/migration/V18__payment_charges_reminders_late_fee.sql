-- Section 1 "Getting paid": charge types, reminders, late fee, UPI direct, receipts, web push.

-- 1. Dues can now be more than rent (deposit, mess, electricity, fines, late fee, other).
ALTER TABLE payment_dues
    ADD COLUMN due_type         VARCHAR(20)  NOT NULL DEFAULT 'RENT',
    ADD COLUMN description      VARCHAR(300) NULL,
    ADD COLUMN parent_due_id    BIGINT       NULL,
    ADD COLUMN last_reminder_on DATE         NULL,
    ADD COLUMN reminder_count   INT          NOT NULL DEFAULT 0;

-- One-off charges (e.g. a fine) don't always belong to a booking.
ALTER TABLE payment_dues ALTER COLUMN booking_id DROP NOT NULL;

ALTER TABLE payment_dues
    ADD CONSTRAINT fk_pd_parent_due FOREIGN KEY (parent_due_id) REFERENCES payment_dues (id);

CREATE INDEX idx_pd_due_type ON payment_dues (due_type);
CREATE INDEX idx_pd_due_date ON payment_dues (due_date);

-- At most one live late-fee due per rent due.
CREATE UNIQUE INDEX uk_pd_late_fee_parent ON payment_dues (parent_due_id)
    WHERE due_type = 'LATE_FEE' AND is_deleted = FALSE;

-- 2. Per-hostel payment settings (owner controlled).
CREATE TABLE hostel_payment_settings (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id                       BIGINT         NOT NULL,
    due_day                         INT            NOT NULL DEFAULT 20, -- matches the previous hard-coded 20th
    auto_generate_dues              BOOLEAN        NOT NULL DEFAULT TRUE,
    reminder_days_before            INT            NOT NULL DEFAULT 3,
    remind_on_due_date              BOOLEAN        NOT NULL DEFAULT TRUE,
    overdue_reminder_interval_days  INT            NOT NULL DEFAULT 3,
    late_fee_enabled                BOOLEAN        NOT NULL DEFAULT FALSE,
    late_fee_enabled_on             DATE           NULL, -- fees only apply to rent due on/after this date (no back-charging)
    late_fee_type                   VARCHAR(10)    NOT NULL DEFAULT 'FLAT',
    late_fee_amount                 DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    late_fee_grace_days             INT            NOT NULL DEFAULT 5,
    late_fee_max_amount             DECIMAL(12, 2) NULL,
    upi_id                          VARCHAR(100)   NULL,
    upi_payee_name                  VARCHAR(100)   NULL,
    landlord_name                   VARCHAR(150)   NULL,
    landlord_pan                    VARCHAR(10)    NULL,
    landlord_address                TEXT           NULL,
    created_at                      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_hps_hostel UNIQUE (hostel_id),
    CONSTRAINT fk_hps_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id),
    CONSTRAINT ck_hps_due_day CHECK (due_day BETWEEN 1 AND 28),
    CONSTRAINT ck_hps_late_fee_type CHECK (late_fee_type IN ('FLAT', 'PER_DAY'))
);

-- 3. Payment records: a resident's "I paid by UPI" claim waits for staff verification.
--    status: SUCCESS | PENDING_VERIFICATION | REJECTED (column already exists, widen for the new value).
ALTER TABLE payment_records ALTER COLUMN status TYPE VARCHAR(30);
ALTER TABLE payment_records ADD COLUMN verified_by BIGINT NULL;
ALTER TABLE payment_records ADD COLUMN verified_at TIMESTAMP NULL;
CREATE INDEX idx_pr_status ON payment_records (status);

-- 4. Browser push subscriptions (one per device/browser).
CREATE TABLE push_subscriptions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id  BIGINT       NOT NULL,
    endpoint      TEXT         NOT NULL,
    p256dh        VARCHAR(200) NOT NULL,
    auth          VARCHAR(100) NOT NULL,
    user_agent    VARCHAR(300) NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_push_endpoint UNIQUE (endpoint),
    CONSTRAINT fk_push_user FOREIGN KEY (auth_user_id) REFERENCES auth_users (id)
);
CREATE INDEX idx_push_user ON push_subscriptions (auth_user_id);
