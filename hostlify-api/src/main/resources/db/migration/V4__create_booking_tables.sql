CREATE TABLE booking_checkins (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hosteller_id          BIGINT         NOT NULL,
  hostel_id             BIGINT         NOT NULL,
  floor_id              BIGINT         NOT NULL,
  room_id               BIGINT         NOT NULL,
  bed_id                BIGINT         NOT NULL,
  checkin_date          DATE           NOT NULL,
  checkout_date         DATE,
  rent_amount           DECIMAL(12, 2) NOT NULL,
  rent_frequency        VARCHAR(20)    NOT NULL DEFAULT 'MONTHLY',
  custom_frequency_days INT,
  advance_amount        DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
  status                VARCHAR(20)    NOT NULL DEFAULT 'ACTIVE',
  checkout_reason       TEXT,
  created_at            TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at            TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted            BOOLEAN     NOT NULL DEFAULT FALSE,
  deleted_at            TIMESTAMP       DEFAULT NULL,
  CONSTRAINT fk_bc_hosteller FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id),
  CONSTRAINT fk_bc_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id),
  CONSTRAINT fk_bc_room FOREIGN KEY (room_id) REFERENCES hostel_rooms (id),
  CONSTRAINT fk_bc_bed FOREIGN KEY (bed_id) REFERENCES hostel_beds (id)
);
CREATE INDEX idx_bc_hosteller_id ON booking_checkins (hosteller_id);
CREATE INDEX idx_bc_hostel_id ON booking_checkins (hostel_id);
CREATE INDEX idx_bc_bed_id ON booking_checkins (bed_id);
CREATE INDEX idx_bc_status ON booking_checkins (status);
