CREATE TABLE payment_records (
  id                   BIGINT         NOT NULL AUTO_INCREMENT PRIMARY KEY,
  hosteller_id         BIGINT         NOT NULL,
  hostel_id            BIGINT         NOT NULL,
  due_id               BIGINT         DEFAULT NULL,
  amount               DECIMAL(12, 2) NOT NULL,
  payment_method       VARCHAR(30)    NOT NULL,
  razorpay_payment_id  VARCHAR(100)   DEFAULT NULL,
  razorpay_order_id    VARCHAR(100)   DEFAULT NULL,
  transaction_ref      VARCHAR(100)   DEFAULT NULL,
  notes                VARCHAR(500)   DEFAULT NULL,
  recorded_by          BIGINT         DEFAULT NULL,
  payment_date         DATE           DEFAULT NULL,
  status               VARCHAR(20)    NOT NULL DEFAULT 'SUCCESS',
  created_at           DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at           DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  is_deleted           TINYINT(1)     NOT NULL DEFAULT 0,
  deleted_at           DATETIME       DEFAULT NULL,
  UNIQUE KEY uk_pr_razorpay_payment_id (razorpay_payment_id),
  CONSTRAINT fk_pr_hosteller FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id),
  CONSTRAINT fk_pr_hostel    FOREIGN KEY (hostel_id)    REFERENCES hostel_hostels (id),
  CONSTRAINT fk_pr_due       FOREIGN KEY (due_id)       REFERENCES payment_dues (id),
  INDEX idx_pr_hosteller_id  (hosteller_id),
  INDEX idx_pr_due_id        (due_id),
  INDEX idx_pr_hostel_id     (hostel_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
