CREATE TABLE hosteller_profiles (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id     BIGINT       NOT NULL,
  first_name       VARCHAR(80)  NOT NULL,
  last_name        VARCHAR(80),
  email            VARCHAR(150) NOT NULL,
  mobile           VARCHAR(15)  NOT NULL,
  alt_mobile       VARCHAR(15),
  date_of_birth    DATE,
  photo_url        VARCHAR(500),
  id_proof_type    VARCHAR(30),
  id_proof_number  VARCHAR(30),
  id_proof_url     VARCHAR(500),
  user_type        VARCHAR(20)  NOT NULL DEFAULT 'GENERAL',
  company_college  VARCHAR(200),
  permanent_address TEXT,
  city             VARCHAR(100),
  pincode          VARCHAR(10),
  status           VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
  joined_date      DATE,
  hostel_id        BIGINT,
  created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted       BOOLEAN   NOT NULL DEFAULT FALSE,
  deleted_at       TIMESTAMP,
  CONSTRAINT fk_hp_auth_user FOREIGN KEY (auth_user_id) REFERENCES auth_users (id)
);
CREATE INDEX idx_hp_auth_user_id ON hosteller_profiles (auth_user_id);
CREATE INDEX idx_hp_hostel_id ON hosteller_profiles (hostel_id);
CREATE INDEX idx_hp_status ON hosteller_profiles (status);

CREATE TABLE hosteller_emergency_contacts (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hosteller_id  BIGINT       NOT NULL,
  name          VARCHAR(150) NOT NULL,
  relationship  VARCHAR(50)  NOT NULL,
  mobile        VARCHAR(15)  NOT NULL,
  alt_mobile    VARCHAR(15),
  created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted    BOOLEAN   NOT NULL DEFAULT FALSE,
  deleted_at    TIMESTAMP     DEFAULT NULL,
  CONSTRAINT fk_hec_hosteller FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id)
);
CREATE INDEX idx_hec_hosteller_id ON hosteller_emergency_contacts (hosteller_id);
