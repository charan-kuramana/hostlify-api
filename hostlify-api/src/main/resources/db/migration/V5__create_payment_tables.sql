CREATE TABLE payment_dues (
  id           BIGINT         NOT NULL AUTO_INCREMENT PRIMARY KEY,
  hosteller_id BIGINT         NOT NULL,
  booking_id   BIGINT         NOT NULL,
  hostel_id    BIGINT         NOT NULL,
  period_month INT            NOT NULL,
  period_year  INT            NOT NULL,
  due_date     DATE           NOT NULL,
  rent_amount  DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
  status       VARCHAR(20)    NOT NULL DEFAULT 'UNPAID',
  created_at   DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   DATETIME       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  is_deleted   TINYINT(1)     NOT NULL DEFAULT 0,
  deleted_at   DATETIME       DEFAULT NULL,
  CONSTRAINT fk_pd_hosteller  FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id),
  CONSTRAINT fk_pd_booking    FOREIGN KEY (booking_id)   REFERENCES booking_checkins (id),
  CONSTRAINT fk_pd_hostel     FOREIGN KEY (hostel_id)    REFERENCES hostel_hostels (id),
  INDEX idx_pd_hosteller_id   (hosteller_id),
  INDEX idx_pd_booking_id     (booking_id),
  INDEX idx_pd_hostel_id      (hostel_id),
  INDEX idx_pd_status         (status),
  INDEX idx_pd_period         (period_year, period_month)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE payment_razorpay_orders (
  id                     BIGINT       NOT NULL AUTO_INCREMENT PRIMARY KEY,
  hosteller_id           BIGINT       NOT NULL,
  due_id                 BIGINT       NOT NULL,
  razorpay_order_id      VARCHAR(100) NOT NULL,
  amount_paise           BIGINT       NOT NULL,
  currency               VARCHAR(5)   NOT NULL DEFAULT 'INR',
  status                 VARCHAR(30)  NOT NULL DEFAULT 'CREATED',
  razorpay_response_json TEXT,
  expires_at             DATETIME     NOT NULL,
  created_at             DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at             DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  is_deleted             TINYINT(1)   NOT NULL DEFAULT 0,
  deleted_at             DATETIME     DEFAULT NULL,
  UNIQUE KEY uk_razorpay_order_id (razorpay_order_id),
  CONSTRAINT fk_pro_hosteller  FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id),
  CONSTRAINT fk_pro_due        FOREIGN KEY (due_id)       REFERENCES payment_dues (id),
  INDEX idx_pro_hosteller_id   (hosteller_id),
  INDEX idx_pro_due_id         (due_id),
  INDEX idx_pro_status         (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
