-- Section 4 "Resident experience": mess opt-in/out + headcount + billing, meal ratings and dish suggestions,
-- complaint SLAs, visitor gate passes, parcel log.

-- 1. Mess settings (owner controlled; off by default).
CREATE TABLE mess_settings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id       BIGINT        NOT NULL,
    enabled         BOOLEAN       NOT NULL DEFAULT FALSE,
    breakfast_time  TIME          NOT NULL DEFAULT '08:00',
    lunch_time      TIME          NOT NULL DEFAULT '13:00',
    dinner_time     TIME          NOT NULL DEFAULT '20:00',
    cutoff_hours    INT           NOT NULL DEFAULT 3,
    breakfast_rate  DECIMAL(8, 2) NOT NULL DEFAULT 0,
    lunch_rate      DECIMAL(8, 2) NOT NULL DEFAULT 0,
    dinner_rate     DECIMAL(8, 2) NOT NULL DEFAULT 0,
    updated_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ms_hostel UNIQUE (hostel_id),
    CONSTRAINT fk_ms_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id),
    CONSTRAINT ck_ms_cutoff CHECK (cutoff_hours BETWEEN 0 AND 48)
);

-- Everyone eats by default; a row here means "I'll skip this meal".
CREATE TABLE mess_optouts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id     BIGINT      NOT NULL,
    hosteller_id  BIGINT      NOT NULL,
    meal_date     DATE        NOT NULL,
    meal_type     VARCHAR(10) NOT NULL,
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_mo_meal UNIQUE (hosteller_id, meal_date, meal_type),
    CONSTRAINT fk_mo_hosteller FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id),
    CONSTRAINT ck_mo_meal CHECK (meal_type IN ('BREAKFAST', 'LUNCH', 'DINNER'))
);
CREATE INDEX idx_mo_hostel_date ON mess_optouts (hostel_id, meal_date);

-- One mess bill run per hostel per month (prevents double billing).
CREATE TABLE mess_bills (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id     BIGINT         NOT NULL,
    period_year   INT            NOT NULL,
    period_month  INT            NOT NULL,
    residents     INT            NOT NULL,
    total_meals   INT            NOT NULL,
    total_amount  DECIMAL(12, 2) NOT NULL,
    created_by    BIGINT         NOT NULL,
    created_at    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_mb_period UNIQUE (hostel_id, period_year, period_month)
);

CREATE TABLE meal_ratings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id     BIGINT       NOT NULL,
    hosteller_id  BIGINT       NOT NULL,
    meal_date     DATE         NOT NULL,
    meal_type     VARCHAR(10)  NOT NULL,
    rating        SMALLINT     NOT NULL,
    comment       VARCHAR(300) NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_mr_meal UNIQUE (hosteller_id, meal_date, meal_type),
    CONSTRAINT ck_mr_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_mr_meal CHECK (meal_type IN ('BREAKFAST', 'LUNCH', 'DINNER'))
);
CREATE INDEX idx_mr_hostel_date ON meal_ratings (hostel_id, meal_date);

CREATE TABLE dish_suggestions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id     BIGINT       NOT NULL,
    hosteller_id  BIGINT       NOT NULL,
    dish          VARCHAR(100) NOT NULL,
    status        VARCHAR(12)  NOT NULL DEFAULT 'OPEN', -- OPEN | ADDED | DISMISSED
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_dsug_hostel ON dish_suggestions (hostel_id, status);

CREATE TABLE dish_suggestion_votes (
    suggestion_id BIGINT    NOT NULL,
    hosteller_id  BIGINT    NOT NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (suggestion_id, hosteller_id),
    CONSTRAINT fk_dsv_suggestion FOREIGN KEY (suggestion_id) REFERENCES dish_suggestions (id) ON DELETE CASCADE
);

-- 2. Complaint SLAs: reported -> acknowledged -> fixed, with a target time per category.
ALTER TABLE complaint_records
    ADD COLUMN acknowledged_at   TIMESTAMP    NULL,
    ADD COLUMN due_at            TIMESTAMP    NULL,
    ADD COLUMN resident_rating   SMALLINT     NULL,
    ADD COLUMN resident_feedback VARCHAR(500) NULL,
    ADD COLUMN overdue_alerted   BOOLEAN      NOT NULL DEFAULT FALSE;

-- Existing complaints get the default 48-hour target; work already started counts as acknowledged.
UPDATE complaint_records SET due_at = created_at + INTERVAL '48 hours' WHERE due_at IS NULL;
UPDATE complaint_records SET acknowledged_at = updated_at WHERE status <> 'OPEN' AND acknowledged_at IS NULL;
-- Don't flood staff with alerts for complaints that were already late before this release.
UPDATE complaint_records SET overdue_alerted = TRUE WHERE due_at < CURRENT_TIMESTAMP;

CREATE TABLE complaint_sla_targets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id     BIGINT      NOT NULL,
    category      VARCHAR(40) NOT NULL,
    target_hours  INT         NOT NULL,
    CONSTRAINT uk_cst_category UNIQUE (hostel_id, category),
    CONSTRAINT ck_cst_hours CHECK (target_hours BETWEEN 1 AND 720)
);

-- 3. Visitor gate passes. EXPECTED (pre-approved by the resident) -> INSIDE -> LEFT, or CANCELLED.
CREATE TABLE visitor_passes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id       BIGINT       NOT NULL,
    hosteller_id    BIGINT       NULL,
    visitor_name    VARCHAR(100) NOT NULL,
    visitor_mobile  VARCHAR(15)  NULL,
    relation        VARCHAR(40)  NULL,
    purpose         VARCHAR(150) NULL,
    visit_date      DATE         NOT NULL,
    pass_code       VARCHAR(6)   NOT NULL,
    status          VARCHAR(12)  NOT NULL DEFAULT 'EXPECTED',
    entry_at        TIMESTAMP    NULL,
    exit_at         TIMESTAMP    NULL,
    entry_by        BIGINT       NULL,
    exit_by         BIGINT       NULL,
    created_by      BIGINT       NOT NULL,
    created_by_role VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_vp_status CHECK (status IN ('EXPECTED', 'INSIDE', 'LEFT', 'CANCELLED'))
);
CREATE INDEX idx_vp_hostel_date ON visitor_passes (hostel_id, visit_date);
CREATE INDEX idx_vp_hosteller ON visitor_passes (hosteller_id);
CREATE INDEX idx_vp_code ON visitor_passes (hostel_id, pass_code);

-- 4. Parcel log: received at the desk -> collected.
CREATE TABLE parcels (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id          BIGINT       NOT NULL,
    hosteller_id       BIGINT       NOT NULL,
    courier            VARCHAR(60)  NULL,
    description        VARCHAR(200) NULL,
    shelf              VARCHAR(30)  NULL,
    status             VARCHAR(12)  NOT NULL DEFAULT 'WAITING', -- WAITING | COLLECTED
    received_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    received_by        BIGINT       NOT NULL,
    collected_at       TIMESTAMP    NULL,
    handed_by          BIGINT       NULL,
    collected_by_name  VARCHAR(100) NULL,
    CONSTRAINT fk_parcel_hosteller FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id)
);
CREATE INDEX idx_parcel_hostel ON parcels (hostel_id, status);
CREATE INDEX idx_parcel_hosteller ON parcels (hosteller_id, status);
