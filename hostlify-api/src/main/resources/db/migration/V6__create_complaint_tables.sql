CREATE TABLE complaint_records (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hosteller_id     BIGINT       NOT NULL,
  hostel_id        BIGINT       NOT NULL,
  room_id          BIGINT,
  category         VARCHAR(40)  NOT NULL,
  title            VARCHAR(200) NOT NULL,
  description      TEXT,
  priority         VARCHAR(20)  NOT NULL DEFAULT 'MEDIUM',
  status           VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
  photo_url        VARCHAR(500),
  assigned_to      BIGINT,
  resolution_notes TEXT,
  resolved_at      TIMESTAMP,
  created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted       BOOLEAN   NOT NULL DEFAULT FALSE,
  deleted_at       TIMESTAMP     DEFAULT NULL,
  CONSTRAINT fk_cr_hosteller FOREIGN KEY (hosteller_id) REFERENCES hosteller_profiles (id),
  CONSTRAINT fk_cr_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id)
);
CREATE INDEX idx_cr_hosteller_id ON complaint_records (hosteller_id);
CREATE INDEX idx_cr_hostel_id ON complaint_records (hostel_id);
CREATE INDEX idx_cr_status ON complaint_records (status);
CREATE INDEX idx_cr_priority ON complaint_records (priority);

CREATE TABLE complaint_maintenance (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hostel_id       BIGINT         NOT NULL,
  room_id         BIGINT,
  reported_by     BIGINT         NOT NULL,
  category        VARCHAR(40)    NOT NULL,
  description     TEXT           NOT NULL,
  estimated_cost  DECIMAL(12, 2),
  actual_cost     DECIMAL(12, 2),
  vendor_name     VARCHAR(200),
  photo_url       VARCHAR(500),
  status          VARCHAR(20)    NOT NULL DEFAULT 'OPEN',
  completed_at    TIMESTAMP,
  created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_deleted      BOOLEAN     NOT NULL DEFAULT FALSE,
  deleted_at      TIMESTAMP       DEFAULT NULL,
  CONSTRAINT fk_cm_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id)
);
CREATE INDEX idx_cm_hostel_id ON complaint_maintenance (hostel_id);
CREATE INDEX idx_cm_status ON complaint_maintenance (status);
