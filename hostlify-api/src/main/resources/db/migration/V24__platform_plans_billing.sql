-- Section 6 "Making money": plan limits, per-bed pricing above the free tier, owner self-serve billing via Razorpay.

-- 1. Platform pricing (single row, super admin edits).
CREATE TABLE platform_settings (
    id              INT            PRIMARY KEY DEFAULT 1,
    free_bed_limit  INT            NOT NULL DEFAULT 30,
    price_per_bed   DECIMAL(8, 2)  NOT NULL DEFAULT 20.00, -- per bed above the free limit, per month
    grace_days      INT            NOT NULL DEFAULT 7,     -- paid limits keep working this long after expiry
    premium_badge   BOOLEAN        NOT NULL DEFAULT TRUE,  -- paid owners get a badge + ranking boost on public pages
    updated_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ps_single CHECK (id = 1),
    CONSTRAINT ck_ps_free CHECK (free_bed_limit BETWEEN 0 AND 10000),
    CONSTRAINT ck_ps_price CHECK (price_per_bed >= 0),
    CONSTRAINT ck_ps_grace CHECK (grace_days BETWEEN 0 AND 60)
);
INSERT INTO platform_settings (id) VALUES (1);

-- 2. Owner payments to the platform (self-serve via Razorpay, or recorded manually by the super admin).
CREATE TABLE platform_payments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id             BIGINT         NOT NULL,
    beds                 INT            NOT NULL,
    months               INT            NOT NULL,
    amount               DECIMAL(12, 2) NOT NULL,
    credit               DECIMAL(12, 2) NOT NULL DEFAULT 0, -- unused value of the previous paid period
    method               VARCHAR(12)    NOT NULL,           -- RAZORPAY | MANUAL
    status               VARCHAR(10)    NOT NULL DEFAULT 'CREATED', -- CREATED | PAID | FAILED
    razorpay_order_id    VARCHAR(60)    NULL,
    razorpay_payment_id  VARCHAR(60)    NULL,
    reference            VARCHAR(100)   NULL,
    period_from          TIMESTAMP      NULL,
    period_to            TIMESTAMP      NULL,
    created_by           BIGINT         NOT NULL,
    created_at           TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at              TIMESTAMP      NULL,
    CONSTRAINT fk_pp_owner FOREIGN KEY (owner_id) REFERENCES hostel_owners (id),
    CONSTRAINT ck_pp_method CHECK (method IN ('RAZORPAY', 'MANUAL')),
    CONSTRAINT ck_pp_status CHECK (status IN ('CREATED', 'PAID', 'FAILED'))
);
CREATE INDEX idx_pp_owner ON platform_payments (owner_id, status);
CREATE UNIQUE INDEX uk_pp_order ON platform_payments (razorpay_order_id) WHERE razorpay_order_id IS NOT NULL;
