-- Section 2 "Filling empty beds": public listing pages, photo gallery, enquiries / visits / waitlist.

-- 1. Public listing: friendly URL + owner on/off switch (off until the owner publishes).
ALTER TABLE hostel_hostels
    ADD COLUMN slug             VARCHAR(160) NULL,
    ADD COLUMN listing_enabled  BOOLEAN      NOT NULL DEFAULT FALSE;

-- e.g. "Bliss PG", Vijayawada, id 1 -> "bliss-pg-vijayawada-1" (id suffix keeps it unique)
UPDATE hostel_hostels
SET slug = trim(both '-' from regexp_replace(lower(name || '-' || city), '[^a-z0-9]+', '-', 'g')) || '-' || id;

ALTER TABLE hostel_hostels ALTER COLUMN slug SET NOT NULL;
CREATE UNIQUE INDEX uk_hostel_slug ON hostel_hostels (slug);

-- 2. Photo gallery.
CREATE TABLE hostel_photos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id   BIGINT       NOT NULL,
    blob_path   VARCHAR(500) NOT NULL,
    caption     VARCHAR(150) NULL,
    sort_order  INT          NOT NULL DEFAULT 0,
    is_cover    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_hp_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id)
);
CREATE INDEX idx_hp_hostel ON hostel_photos (hostel_id, sort_order);

-- 3. Enquiries from the public page (also used for visits and the waitlist).
CREATE TABLE hostel_enquiries (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id           BIGINT       NOT NULL,
    name                VARCHAR(120) NOT NULL,
    mobile              VARCHAR(15)  NOT NULL,
    email               VARCHAR(150) NULL,
    gender              VARCHAR(10)  NULL,
    room_type           VARCHAR(30)  NULL,
    move_in_date        DATE         NULL,
    message             VARCHAR(1000) NULL,
    visit_date          DATE         NULL,
    visit_slot          VARCHAR(20)  NULL,          -- MORNING | AFTERNOON | EVENING
    -- NEW | CONTACTED | VISIT_SCHEDULED | WAITLIST | JOINED | LOST
    status              VARCHAR(20)  NOT NULL DEFAULT 'NEW',
    staff_notes         VARCHAR(2000) NULL,
    source              VARCHAR(20)  NOT NULL DEFAULT 'PUBLIC_PAGE',
    last_contacted_at   TIMESTAMP    NULL,
    waitlist_nudged_on  DATE         NULL,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_he_hostel FOREIGN KEY (hostel_id) REFERENCES hostel_hostels (id),
    CONSTRAINT ck_he_status CHECK (status IN ('NEW','CONTACTED','VISIT_SCHEDULED','WAITLIST','JOINED','LOST'))
);
CREATE INDEX idx_he_hostel_status ON hostel_enquiries (hostel_id, status);
CREATE INDEX idx_he_mobile ON hostel_enquiries (mobile);
